import puppeteer from 'puppeteer-core';
// Opens v3p2's console from the header, runs commands, and captures it; then the /cli page.
const base = process.env.BASE || 'http://127.0.0.1:4190';
const browser = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: 'new', userDataDir: 'C:/Users/muthu/AppData/Local/Temp/pp-tools', args: ['--no-sandbox', '--no-first-run'] });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.setViewport({ width: 1440, height: 900 });
await page.evaluateOnNewDocument(() => { try { sessionStorage.setItem('ff3-seen', '1'); } catch (e) {} });
await page.goto(base + '/team', { waitUntil: 'networkidle2' });
await page.waitForFunction('window.__ffReady === true', { timeout: 40000 });
await new Promise((r) => setTimeout(r, 1500));
await page.click('.hd-cli-btn');
await page.waitForSelector('.sl-cli-in input', { timeout: 10000 });
await new Promise((r) => setTimeout(r, 700));
await page.type('.sl-cli-in input', 'team');
await page.keyboard.press('Enter');
await page.type('.sl-cli-in input', 'cre');
await page.keyboard.press('Tab');
await page.keyboard.press('Enter');
await new Promise((r) => setTimeout(r, 500));
await page.screenshot({ path: 'shots/cli-0.png' });
await page.keyboard.press('Escape');
await new Promise((r) => setTimeout(r, 400));
const closed = await page.evaluate(() => !document.querySelector('.sl-cli'));
await page.goto(base + '/cli', { waitUntil: 'networkidle2' });
await page.waitForFunction('window.__ffReady === true', { timeout: 40000 });
await new Promise((r) => setTimeout(r, 1500));
await page.type('.sl-cli-in input', 'domains');
await page.keyboard.press('Enter');
await new Promise((r) => setTimeout(r, 400));
await page.evaluate(() => document.querySelector('.cli-page').scrollIntoView());
await new Promise((r) => setTimeout(r, 800));
await page.screenshot({ path: 'shots/cli-1.png' });
console.log('esc closes:', closed, 'errors', errors);
await browser.close();
